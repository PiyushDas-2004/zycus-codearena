import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..', '..');
const MIGRATIONS = join(ROOT, 'supabase', 'migrations');
const SEED_PARTS = join(ROOT, 'supabase', 'seed', 'parts');

export const sectionStart = (name: string) => `-- ┌── ${name}`;
export const sectionEnd = (name: string) => `-- └── end of ${name}`;

/**
 * Applied migrations are recorded in the same table the Supabase CLI uses, so the project can move
 * to `supabase db push` / the GitHub integration later without re-running anything.
 */
const TRACKING = 'supabase_migrations.schema_migrations';

/**
 * Databases set up with the Phase 2 script (before migrations were recorded) contain exactly the
 * migrations up to and including this version.
 */
export const LEGACY_BASELINE = '20261009000006';

const MIGRATION_TAG = '$codearena_migration$';
const BLOCK_TAG = '$codearena$';

export interface Migration {
  version: string;
  name: string;
  file: string;
  sql: string;
  /** First line `-- pglite:skip`: needs Supabase-only extensions (pg_cron). */
  pgliteSkip: boolean;
}

export function listMigrations(): Migration[] {
  return readdirSync(MIGRATIONS)
    .filter((f) => f.endsWith('.sql'))
    .sort()
    .map((file) => {
      const m = /^(\d{14})_(.+)\.sql$/.exec(file);
      if (!m) throw new Error(`Migration file name must be <14-digit version>_<name>.sql: ${file}`);
      const sql = readFileSync(join(MIGRATIONS, file), 'utf8').replace(/\r\n/g, '\n').trim();
      for (const tag of [MIGRATION_TAG, BLOCK_TAG]) {
        if (sql.includes(tag)) throw new Error(`${file} must not contain the reserved quote tag ${tag}`);
      }
      if (/^\s*(begin|commit|rollback)\s*;/im.test(sql)) {
        throw new Error(`${file} must not contain transaction control; the bundle is one transaction`);
      }
      return { version: m[1]!, name: m[2]!, file, sql, pgliteSkip: sql.startsWith('-- pglite:skip') };
    });
}

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

/** Runs `body` (SQL) once, recording `version` — skipped when already recorded. */
function guardedBlock(label: string, version: string, name: string, body: string): string {
  return [
    sectionStart(label),
    `do ${BLOCK_TAG}`,
    'begin',
    `  if exists (select 1 from ${TRACKING} where version = ${lit(version)}) then`,
    `    raise notice 'Already applied: %', ${lit(label)};`,
    '    return;',
    '  end if;',
    `  execute ${MIGRATION_TAG}`,
    body,
    `${MIGRATION_TAG};`,
    `  insert into ${TRACKING} (version, name) values (${lit(version)}, ${lit(name)});`,
    'end',
    `${BLOCK_TAG};`,
    sectionEnd(label),
    '',
  ].join('\n');
}

export interface DatabaseScriptOptions {
  /** Leave out some migrations (tests: the pg_cron ones, which PGlite cannot run). */
  exclude?: (m: Migration) => boolean;
}

/** Migrations per schema script stay under this size: the SQL Editor fails on large scripts. */
const SCHEMA_SCRIPT_BUDGET = 110_000;

/** Splits the migrations, in order, into groups that each fit one SQL Editor script. */
function schemaGroups(all: Migration[]): Migration[][] {
  const groups: Migration[][] = [[]];
  let size = 0;
  for (const m of all) {
    if (size + m.sql.length > SCHEMA_SCRIPT_BUDGET && groups.at(-1)!.length) {
      groups.push([]);
      size = 0;
    }
    groups.at(-1)!.push(m);
    size += m.sql.length;
  }
  return groups;
}

export const schemaFileName = (i: number) => `${String(i + 1).padStart(2, '0')}-schema-${i + 1}.sql`;

/**
 * The schema scripts for the Supabase SQL Editor: they install CodeArena on an empty project or
 * upgrade an existing one. Every migration not yet recorded is applied, in order; each script is ONE
 * transaction (all or nothing) and safe to run again. They are split by size (the SQL Editor fails
 * on very large scripts, "Failed to fetch"), and each later script checks that the one before it ran.
 * The questions and templates follow as separate scripts (buildDatabaseParts).
 */
export function buildSchemaScripts(opts: DatabaseScriptOptions = {}): string[] {
  const all = listMigrations();
  const legacy = all.filter((m) => m.version <= LEGACY_BASELINE);
  const groups = schemaGroups(all);

  return groups.map((group, g) => {
    const migrations = group.filter((m) => !opts.exclude?.(m));
    const previous = groups
      .slice(0, g)
      .flat()
      .filter((m) => !opts.exclude?.(m))
      .at(-1);
    const last = g === groups.length - 1;
    const lines: string[] = [
      '-- ════════════════════════════════════════════════════════════════════════════',
      `-- Zycus CodeArena: database install / upgrade, schema script ${g + 1} of ${groups.length}.`,
      '-- GENERATED by `npm run sql:bundle`. Do not edit; edit supabase/migrations instead.',
      '-- Run the numbered files in this folder in order: Dashboard → SQL Editor → New query → Run.',
      '-- Safe to run again: migrations that are already applied are skipped, and this script runs',
      '-- in ONE transaction (all or nothing).',
      '-- Prerequisite: Dashboard → Integrations → Cron → Enable (pg_cron).',
      '-- ════════════════════════════════════════════════════════════════════════════',
      'begin;',
      '',
      'create schema if not exists supabase_migrations;',
      `create table if not exists ${TRACKING} (version text not null primary key, statements text[], name text);`,
      '',
      `-- Databases installed before migrations were recorded contain everything up to ${LEGACY_BASELINE}.`,
      `insert into ${TRACKING} (version, name)`,
      `select v.version, v.name from (values ${legacy.map((m) => `(${lit(m.version)}, ${lit(m.name)})`).join(', ')}) as v(version, name)`,
      "where to_regclass('public.sessions') is not null",
      `  and not exists (select 1 from ${TRACKING} t where t.version <= ${lit(LEGACY_BASELINE)})`,
      'on conflict (version) do nothing;',
      '',
    ];
    if (previous) {
      lines.push(
        `do ${BLOCK_TAG}`,
        'begin',
        `  if not exists (select 1 from ${TRACKING} where version = ${lit(previous.version)}) then`,
        `    raise exception 'Run ${schemaFileName(g - 1)} first: this script continues where it ends.';`,
        '  end if;',
        'end',
        `${BLOCK_TAG};`,
        '',
      );
    }
    for (const m of migrations) lines.push(guardedBlock(m.file, m.version, m.name, m.sql));
    lines.push(
      'commit;',
      '',
      last
        ? `select 'Schema is ready. Now run the next file.' as status,`
        : `select 'Schema script ${g + 1} of ${groups.length} is done. Now run the next file.' as status,`,
      `       (select max(version) from ${TRACKING}) as schema_version;`,
      '',
    );
    return lines.join('\n');
  });
}

/** All schema scripts as one text (checks on its content). */
export const buildDatabaseScript = (opts: DatabaseScriptOptions = {}) => buildSchemaScripts(opts).join('\n');

export interface DatabasePart {
  /** File name, numbered in the order the parts must run. */
  file: string;
  sql: string;
}

/**
 * Everything the SQL Editor runs, in order: the schema, then one script per question, then one per
 * template (supabase/seed/parts, built by npm run seed:build). Each is its own transaction and safe
 * to run again; each stays small enough for the SQL Editor.
 */
export function buildDatabaseParts(opts: DatabaseScriptOptions = {}): DatabasePart[] {
  if (!existsSync(SEED_PARTS)) throw new Error('supabase/seed/parts is missing: run npm run seed:build');
  const seedFiles = readdirSync(SEED_PARTS)
    .filter((f) => f.endsWith('.sql'))
    .sort((a, b) =>
      a.startsWith('question-') === b.startsWith('question-')
        ? a.localeCompare(b)
        : a.startsWith('question-')
          ? -1
          : 1,
    );
  const pad = (n: number) => String(n).padStart(2, '0');
  const schema = buildSchemaScripts(opts).map((sql, i) => ({ file: schemaFileName(i), sql }));
  return [
    ...schema,
    ...seedFiles.map((f, i) => ({
      file: `${pad(schema.length + i + 1)}-${f}`,
      sql: readFileSync(join(SEED_PARTS, f), 'utf8').replace(/\r\n/g, '\n'),
    })),
  ];
}
