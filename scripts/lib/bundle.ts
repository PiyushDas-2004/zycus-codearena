import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..', '..');
const MIGRATIONS = join(ROOT, 'supabase', 'migrations');
const SEED = join(ROOT, 'supabase', 'seed', 'seed.sql');

export const sectionStart = (name: string) => `-- ┌── ${name}`;
export const sectionEnd = (name: string) => `-- └── end of ${name}`;

/**
 * Applied migrations are recorded in the same table the Supabase CLI uses, so the project can move
 * to `supabase db push` / the GitHub integration later without re-running anything.
 */
const TRACKING = 'supabase_migrations.schema_migrations';

/**
 * Databases set up with the Phase 2 script (before migrations were recorded) contain exactly the
 * migrations up to and including this version.
 */
export const LEGACY_BASELINE = '20261009000006';

const MIGRATION_TAG = '$codearena_migration$';
const BLOCK_TAG = '$codearena$';

export interface Migration {
  version: string;
  name: string;
  file: string;
  sql: string;
  /** First line `-- pglite:skip`: needs Supabase-only extensions (pg_cron). */
  pgliteSkip: boolean;
}

export function listMigrations(): Migration[] {
  return readdirSync(MIGRATIONS)
    .filter((f) => f.endsWith('.sql'))
    .sort()
    .map((file) => {
      const m = /^(\d{14})_(.+)\.sql$/.exec(file);
      if (!m) throw new Error(`Migration file name must be <14-digit version>_<name>.sql: ${file}`);
      const sql = readFileSync(join(MIGRATIONS, file), 'utf8').replace(/\r\n/g, '\n').trim();
      for (const tag of [MIGRATION_TAG, BLOCK_TAG]) {
        if (sql.includes(tag)) throw new Error(`${file} must not contain the reserved quote tag ${tag}`);
      }
      if (/^\s*(begin|commit|rollback)\s*;/im.test(sql)) {
        throw new Error(`${file} must not contain transaction control; the bundle is one transaction`);
      }
      return { version: m[1]!, name: m[2]!, file, sql, pgliteSkip: sql.startsWith('-- pglite:skip') };
    });
}

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

/** Runs `body` (SQL) once, recording `version` — skipped when already recorded. */
function guardedBlock(label: string, version: string, name: string, body: string): string {
  return [
    sectionStart(label),
    `do ${BLOCK_TAG}`,
    'begin',
    `  if exists (select 1 from ${TRACKING} where version = ${lit(version)}) then`,
    `    raise notice 'Already applied: %', ${lit(label)};`,
    '    return;',
    '  end if;',
    `  execute ${MIGRATION_TAG}`,
    body,
    `${MIGRATION_TAG};`,
    `  insert into ${TRACKING} (version, name) values (${lit(version)}, ${lit(name)});`,
    'end',
    `${BLOCK_TAG};`,
    sectionEnd(label),
    '',
  ].join('\n');
}

export interface DatabaseScriptOptions {
  /** Leave out some migrations (tests: the pg_cron ones, which PGlite cannot run). */
  exclude?: (m: Migration) => boolean;
}

/**
 * ONE script for the Supabase SQL Editor that installs CodeArena on an empty project or upgrades an
 * existing one: every migration not yet recorded is applied, in order, in a single transaction (all
 * or nothing). Sample questions are loaded only on a fresh install. Safe to run again.
 */
export function buildDatabaseScript(opts: DatabaseScriptOptions = {}): string {
  const all = listMigrations();
  const migrations = all.filter((m) => !opts.exclude?.(m));
  const legacy = all.filter((m) => m.version <= LEGACY_BASELINE);
  const seed = readFileSync(SEED, 'utf8')
    .replace(/\r\n/g, '\n')
    .replace(/^begin;\s*$/m, '')
    .replace(/^commit;\s*$/m, '')
    .trim();
  if (seed.includes(MIGRATION_TAG) || seed.includes(BLOCK_TAG)) {
    throw new Error('seed.sql must not contain the reserved quote tags');
  }

  const parts: string[] = [
    '-- ════════════════════════════════════════════════════════════════════════════',
    '-- Zycus CodeArena: database install / upgrade.',
    '-- GENERATED by `npm run sql:bundle`. Do not edit; edit supabase/migrations instead.',
    '-- Run in Dashboard → SQL Editor → New query → Run. Safe to run again: migrations that are',
    '-- already applied are skipped, and everything runs in ONE transaction (all or nothing).',
    '-- Prerequisite: Dashboard → Integrations → Cron → Enable (pg_cron).',
    '-- ════════════════════════════════════════════════════════════════════════════',
    'begin;',
    '',
    'create schema if not exists supabase_migrations;',
    `create table if not exists ${TRACKING} (version text not null primary key, statements text[], name text);`,
    '',
    '-- Sample data only on a fresh install (never overwrites questions edited by admins).',
    "select set_config('codearena.fresh_install', case when to_regclass('public.sessions') is null then 'on' else 'off' end, true);",
    '',
    `-- Databases installed before migrations were recorded contain everything up to ${LEGACY_BASELINE}.`,
    `insert into ${TRACKING} (version, name)`,
    `select v.version, v.name from (values ${legacy.map((m) => `(${lit(m.version)}, ${lit(m.name)})`).join(', ')}) as v(version, name)`,
    "where to_regclass('public.sessions') is not null",
    `  and not exists (select 1 from ${TRACKING} t where t.version <= ${lit(LEGACY_BASELINE)})`,
    'on conflict (version) do nothing;',
    '',
  ];
  for (const m of migrations) parts.push(guardedBlock(m.file, m.version, m.name, m.sql));
  parts.push(
    sectionStart('seed.sql'),
    `do ${BLOCK_TAG}`,
    'begin',
    "  if current_setting('codearena.fresh_install', true) is distinct from 'on' then",
    "    raise notice 'Existing installation: sample questions not loaded';",
    '    return;',
    '  end if;',
    `  execute ${MIGRATION_TAG}`,
    seed,
    `${MIGRATION_TAG};`,
    'end',
    `${BLOCK_TAG};`,
    sectionEnd('seed.sql'),
    '',
    'commit;',
    '',
    `select 'Zycus CodeArena database is ready' as status,`,
    `       (select max(version) from ${TRACKING}) as schema_version;`,
    '',
  );
  return parts.join('\n');
}
