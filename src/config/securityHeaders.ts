/**
 * HTTP security headers for the deployed site. vite.config.ts writes them to dist/_headers
 * (Cloudflare Pages format) at build time and applies the same headers in `vite preview`, so what
 * is tested locally is exactly what is served. Pure data: imported by vite.config.ts (Node).
 *
 * Why each relaxation exists:
 * - script-src 'wasm-unsafe-eval': WebAssembly for on-device face detection (no JS eval anywhere;
 *   eval/new Function are lint errors and MediaPipe's loader uses neither).
 * - style-src 'unsafe-inline': Monaco and React set inline style attributes (no inline scripts).
 * - img-src data: blob:: the watermark is an inline SVG; snapshots are drawn from a canvas.
 * - connect-src: only this origin and the configured Supabase project (HTTPS + WSS for Realtime).
 */
export function contentSecurityPolicy(supabaseUrl: string): string {
  const supabase = supabaseUrl ? [supabaseUrl, supabaseUrl.replace(/^https:/, 'wss:')] : [];
  const directives: [string, string[]][] = [
    ['default-src', ["'self'"]],
    ['script-src', ["'self'", "'wasm-unsafe-eval'"]],
    ['style-src', ["'self'", "'unsafe-inline'"]],
    ['img-src', ["'self'", 'data:', 'blob:']],
    ['font-src', ["'self'", 'data:']],
    ['connect-src', ["'self'", ...supabase]],
    ['worker-src', ["'self'", 'blob:']],
    ['media-src', ["'self'", 'blob:']],
    ['manifest-src', ["'self'"]],
    ['object-src', ["'none'"]],
    ['frame-src', ["'none'"]],
    ['frame-ancestors', ["'none'"]],
    ['base-uri', ["'none'"]],
    ['form-action', ["'self'"]],
    ['upgrade-insecure-requests', []],
  ];
  return directives.map(([name, values]) => [name, ...values].join(' ')).join('; ');
}

export function securityHeaders(supabaseUrl: string): Record<string, string> {
  return {
    'Content-Security-Policy': contentSecurityPolicy(supabaseUrl),
    'X-Content-Type-Options': 'nosniff',
    'X-Frame-Options': 'DENY',
    'Referrer-Policy': 'no-referrer',
    // Camera/microphone/full screen for proctoring; window-management keeps screen.isExtended working.
    'Permissions-Policy':
      'camera=(self), microphone=(self), fullscreen=(self), window-management=(self), display-capture=(), geolocation=(), payment=(), usb=(), serial=(), bluetooth=(), hid=()',
    'Cross-Origin-Opener-Policy': 'same-origin',
    'Cross-Origin-Resource-Policy': 'same-origin',
    'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
    'X-Robots-Tag': 'noindex, nofollow',
  };
}

/** Cloudflare Pages `_headers` file: security headers everywhere, long caching for hashed assets. */
export function cloudflareHeadersFile(supabaseUrl: string): string {
  const lines = ['# Generated by vite.config.ts from src/config/securityHeaders.ts — do not edit.', '/*'];
  for (const [k, v] of Object.entries(securityHeaders(supabaseUrl))) lines.push(`  ${k}: ${v}`);
  lines.push('/assets/*', '  Cache-Control: public, max-age=31536000, immutable');
  lines.push('/models/*', '  Cache-Control: public, max-age=604800');
  return `${lines.join('\n')}\n`;
}
